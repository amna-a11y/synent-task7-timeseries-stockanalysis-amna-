import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from statsmodels.tsa.seasonal import seasonal_decompose
from statsmodels.tsa.stattools import adfuller
from statsmodels.graphics.tsaplots import plot_acf
import warnings
warnings.filterwarnings('ignore')

from google.colab import files
import zipfile, io, os

plt.rcParams['figure.figsize'] = (14, 5)
sns.set_theme(style="whitegrid")

print("✅ Libraries loaded.")


# ── CELL 2: Upload, Extract & Load Dataset ──────────────────
print("📂 Upload ZIP file")
uploaded = files.upload()

zip_filename = list(uploaded.keys())[0]

with zipfile.ZipFile(io.BytesIO(uploaded[zip_filename]), 'r') as zip_ref:
    zip_ref.extractall()

print("✅ ZIP extracted")

# Find CSV
csv_file = None
for f in os.listdir():
    if f.endswith(".csv"):
        csv_file = f
        break

if csv_file is None:
    raise FileNotFoundError("CSV not found!")

print("📄 Found:", csv_file)

df = pd.read_csv(csv_file, encoding='latin1')
print("✅ Dataset Loaded:", df.shape)


# ── CELL 3: Data Cleaning ───────────────────────────────────
df['Date'] = pd.to_datetime(df['Date'], utc=True, errors='coerce').dt.tz_convert(None)

df = df[['Date', 'Open', 'High', 'Low', 'Close', 'Volume',
         'Brand_Name', 'Ticker', 'Industry_Tag', 'Country']]

df.rename(columns={'Brand_Name': 'Brand', 'Industry_Tag': 'Industry'}, inplace=True)

df = df.dropna(subset=['Date', 'Close'])
df = df.sort_values(['Ticker', 'Date'])

print("✅ Data cleaned")


# ── CELL 4: Select Stock ────────────────────────────────────
TICKER = 'AMZN'

stock = df[df['Ticker'] == TICKER].copy()
stock = stock.set_index('Date').sort_index()
stock = stock[~stock.index.duplicated()]

close = stock['Close'].asfreq('D').ffill()

print("Analyzing:", TICKER)


# ── CELL 5: Calculations ────────────────────────────────────
returns = close.pct_change().dropna()
weekly = close.resample('W').mean().dropna()

result = adfuller(close.dropna())
total_return = (close.iloc[-1] / close.iloc[0] - 1) * 100


# ── CELL 6: FINAL DASHBOARD IMAGE ───────────────────────────
fig, axes = plt.subplots(3, 2, figsize=(18, 12))

# 1. Price + Moving Avg
axes[0,0].plot(close, label='Close')
axes[0,0].plot(close.rolling(30).mean(), label='30 MA')
axes[0,0].plot(close.rolling(90).mean(), label='90 MA')
axes[0,0].set_title("Price & Moving Average")
axes[0,0].legend()

# 2. Returns
axes[0,1].plot(returns)
axes[0,1].set_title("Daily Returns")

# 3. Industry Avg
df.groupby('Industry')['Close'].mean().sort_values().tail(5).plot(kind='barh', ax=axes[1,0])
axes[1,0].set_title("Top Industries")

# 4. ACF
plot_acf(returns, ax=axes[1,1])

# 5. Weekly Trend
axes[2,0].plot(weekly)
axes[2,0].set_title("Weekly Trend")

# 6. Summary Text
axes[2,1].axis('off')
summary_text = f"""
Ticker: {TICKER}
Total Return: {round(total_return,2)}%
ADF p-value: {round(result[1],4)}
"""

axes[2,1].text(0.1, 0.5, summary_text, fontsize=12)

plt.tight_layout()

# ── SAVE IMAGE ───────────────────────────────────────────────
output_path = "FINAL_DASHBOARD.png"
plt.savefig(output_path, dpi=300, bbox_inches='tight')

plt.show()

print(f"✅ IMAGE SAVED: {output_path}")


